import React from 'react';
import { OverallStatus, AiStatus, BiomarkerFlag } from '../../types/api';
import { CheckCircle2, Clock, AlertTriangle, XCircle, Sparkles, FileText, MinusCircle } from 'lucide-react';

interface OverallStatusBadgeProps {
  status?: OverallStatus | string | null;
  size?: 'sm' | 'md';
}

export const OverallStatusBadge: React.FC<OverallStatusBadgeProps> = ({ status, size = 'sm' }) => {
  const textSize = size === 'sm' ? 'text-xs px-2 py-0.5' : 'text-sm px-2.5 py-1';
  const iconSize = size === 'sm' ? 'w-3 h-3' : 'w-3.5 h-3.5';

  switch (status) {
    case 'COMPLETED':
      return (
        <span
          className={`inline-flex items-center gap-1.5 font-medium rounded-full bg-emerald-50 text-emerald-800 border border-emerald-200 ${textSize}`}
          role="status"
          aria-label="Analysis Status: Completed"
        >
          <CheckCircle2 className={`${iconSize} text-emerald-600 shrink-0`} aria-hidden="true" />
          <span>Completed</span>
        </span>
      );

    case 'PENDING':
      return (
        <span
          className={`inline-flex items-center gap-1.5 font-medium rounded-full bg-blue-50 text-blue-800 border border-blue-200 ${textSize}`}
          role="status"
          aria-label="Analysis Status: In Progress / Pending"
        >
          <Clock className={`${iconSize} text-blue-600 animate-spin shrink-0`} aria-hidden="true" />
          <span>Analyzing...</span>
        </span>
      );

    case 'DEGRADED':
      return (
        <span
          className={`inline-flex items-center gap-1.5 font-medium rounded-full bg-amber-50 text-amber-800 border border-amber-200 ${textSize}`}
          role="status"
          aria-label="Analysis Status: Degraded or Fallback Applied"
        >
          <AlertTriangle className={`${iconSize} text-amber-600 shrink-0`} aria-hidden="true" />
          <span>Degraded / Fallback</span>
        </span>
      );

    case 'FAILED':
      return (
        <span
          className={`inline-flex items-center gap-1.5 font-medium rounded-full bg-rose-50 text-rose-800 border border-rose-200 ${textSize}`}
          role="status"
          aria-label="Analysis Status: Failed"
        >
          <XCircle className={`${iconSize} text-rose-600 shrink-0`} aria-hidden="true" />
          <span>Failed</span>
        </span>
      );

    case 'NOT_RUN':
    default:
      return (
        <span
          className={`inline-flex items-center gap-1.5 font-medium rounded-full bg-slate-100 text-slate-700 border border-slate-200 ${textSize}`}
          role="status"
          aria-label="Analysis Status: Not Run"
        >
          <MinusCircle className={`${iconSize} text-slate-500 shrink-0`} aria-hidden="true" />
          <span>Not Run</span>
        </span>
      );
  }
};

interface AiStatusBadgeProps {
  status?: AiStatus | string | null;
  generationLabel?: string | null;
  size?: 'sm' | 'md';
}

export const AiStatusBadge: React.FC<AiStatusBadgeProps> = ({
  status,
  generationLabel,
  size = 'sm',
}) => {
  const textSize = size === 'sm' ? 'text-xs px-2 py-0.5' : 'text-sm px-2.5 py-1';
  const iconSize = size === 'sm' ? 'w-3 h-3' : 'w-3.5 h-3.5';

  const isAiGenerated =
    status === 'SUCCEEDED' || generationLabel === 'AI_GENERATED';
  const isFallback =
    status === 'FALLBACK' || generationLabel === 'DETERMINISTIC_FALLBACK';

  if (isAiGenerated) {
    return (
      <span
        className={`inline-flex items-center gap-1.5 font-medium rounded-full bg-indigo-50 text-indigo-800 border border-indigo-200 ${textSize}`}
        role="status"
        aria-label="AI Remarks: AI Generated by Ollama llama3.2:3b"
      >
        <Sparkles className={`${iconSize} text-indigo-600 shrink-0`} aria-hidden="true" />
        <span>AI Generated</span>
      </span>
    );
  }

  if (isFallback) {
    return (
      <span
        className={`inline-flex items-center gap-1.5 font-medium rounded-full bg-slate-100 text-slate-800 border border-slate-300 ${textSize}`}
        role="status"
        aria-label="AI Remarks: Template Fallback (Not AI Generated)"
      >
        <FileText className={`${iconSize} text-slate-600 shrink-0`} aria-hidden="true" />
        <span>Template Fallback</span>
      </span>
    );
  }

  return (
    <span
      className={`inline-flex items-center gap-1.5 font-medium rounded-full bg-slate-100 text-slate-500 border border-slate-200 ${textSize}`}
      role="status"
      aria-label="AI Remarks: Pending or Not Run"
    >
      <span>AI Not Run</span>
    </span>
  );
};

interface BiomarkerFlagBadgeProps {
  flag?: BiomarkerFlag | string | null;
}

export const BiomarkerFlagBadge: React.FC<BiomarkerFlagBadgeProps> = ({ flag }) => {
  const clean = (flag || 'unknown').toLowerCase();

  switch (clean) {
    case 'normal':
      return (
        <span className="inline-flex items-center px-2 py-0.5 rounded text-xs font-semibold bg-emerald-100 text-emerald-800">
          Normal
        </span>
      );
    case 'high':
      return (
        <span className="inline-flex items-center px-2 py-0.5 rounded text-xs font-semibold bg-amber-100 text-amber-800">
          Elevated (High)
        </span>
      );
    case 'low':
      return (
        <span className="inline-flex items-center px-2 py-0.5 rounded text-xs font-semibold bg-sky-100 text-sky-800">
          Low
        </span>
      );
    case 'unknown':
    default:
      return (
        <span className="inline-flex items-center px-2 py-0.5 rounded text-xs font-semibold bg-slate-100 text-slate-700">
          Uncategorized
        </span>
      );
  }
};
