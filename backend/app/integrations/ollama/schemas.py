from typing import Any

from pydantic import BaseModel, ConfigDict, Field


class AnalyteRemark(BaseModel):
    """Structured remark for a single laboratory biomarker based on TestWell output."""

    model_config = ConfigDict(extra="forbid")

    analyte: str = Field(..., description="Analyte name: glucose, haemoglobin, or cholesterol")
    observation_id: str = Field(
        ...,
        description="Identifier of the provider observation: obs-glucose, obs-haemoglobin, obs-cholesterol",
    )
    provider_flag: str = Field(..., description="Provider flag: low, normal, high, or unknown")
    summary: str = Field(
        ...,
        min_length=1,
        max_length=250,
        description="Short neutral summary of this analyte's provider result",
    )


class AiRemarksPayload(BaseModel):
    """Contract for structured AI remarks generated by local Ollama llama3.2:3b."""

    model_config = ConfigDict(extra="forbid")

    summary: str = Field(
        ...,
        min_length=1,
        max_length=500,
        description="Concise overall plain-language summary based only on supplied provider observations",
    )
    analyte_remarks: list[AnalyteRemark] = Field(
        ...,
        min_length=1,
        max_length=10,
        description="Individual analyte observations summarized from provider facts",
    )
    source_observation_ids: list[str] = Field(
        ...,
        min_length=1,
        description="Observation IDs referenced from provider output",
    )
    caveat_codes: list[str] = Field(
        ...,
        description="Standardized caveat codes: FASTING_STATUS_NOT_CONFIRMED, DEMOGRAPHIC_CONTEXT_NOT_CONFIRMED, UNIT_ASSUMPTION",
    )
    generation_label: str = Field(
        default="AI_GENERATED",
        description="Must be strictly AI_GENERATED",
    )


# --- Ollama API Transport Schemas ---


class OllamaGenerateRequest(BaseModel):
    """Payload for Ollama POST /api/generate endpoint."""

    model_config = ConfigDict(extra="ignore")

    model: str
    prompt: str
    system: str | None = None
    format: dict[str, Any] | str | None = None
    stream: bool = False
    options: dict[str, Any] | None = None
    keep_alive: str | None = "5m"


class OllamaGenerateResponse(BaseModel):
    """Response envelope from Ollama POST /api/generate."""

    model_config = ConfigDict(extra="ignore")

    model: str
    response: str
    done: bool = True
    total_duration: int | None = None
    load_duration: int | None = None
    prompt_eval_count: int | None = None
    eval_count: int | None = None
    eval_duration: int | None = None
